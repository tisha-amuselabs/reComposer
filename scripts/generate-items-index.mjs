#!/usr/bin/env node
// Scans src/app/vansh/data/items/*.ts and regenerates index.ts so a new item
// file becomes playable (and shows up in the demo picker) without ever
// hand-editing the ITEMS array. Run directly, or imported by scripts/dev.mjs
// to also re-run on file changes while the dev server is up.

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
export const itemsDir = path.join(__dirname, "..", "src/app/vansh/data/items");
const indexPath = path.join(itemsDir, "index.ts");

const EXPORT_PATTERN = /export const ([A-Z][A-Z0-9_]*)\s*:\s*ItemOfDay/;

export function generate() {
  const files = readdirSync(itemsDir)
    .filter((f) => f.endsWith(".ts") && f !== "index.ts")
    .sort();

  const entries = [];
  for (const file of files) {
    const contents = readFileSync(path.join(itemsDir, file), "utf8");
    const match = contents.match(EXPORT_PATTERN);
    if (!match) {
      console.warn(
        `[generate-items-index] Skipping ${file}: no "export const NAME: ItemOfDay" found.`
      );
      continue;
    }
    entries.push({ exportName: match[1], moduleName: file.replace(/\.ts$/, "") });
  }

  if (entries.length === 0) {
    console.warn("[generate-items-index] No item files found — leaving index.ts untouched.");
    return;
  }

  const imports = entries
    .map((e) => `import { ${e.exportName} } from "./${e.moduleName}";`)
    .join("\n");
  const list = entries.map((e) => `  ${e.exportName},`).join("\n");

  const content = `// AUTO-GENERATED by scripts/generate-items-index.mjs — do not edit by hand.
// Add a new item by dropping a file in this folder that exports
// \`export const YOUR_NAME: ItemOfDay = {...}\` — it's picked up automatically
// the next time the dev server starts, and live while \`npm run dev\` is
// already running.
import type { ItemOfDay } from "../../types/item";
${imports}

export const ITEMS: ItemOfDay[] = [
${list}
];

export function itemById(id: string): ItemOfDay {
  const found = ITEMS.find((item) => item.id === id);
  return found ?? ITEMS[0];
}
`;

  const existing = existsSync(indexPath) ? readFileSync(indexPath, "utf8") : null;
  if (existing !== content) {
    writeFileSync(indexPath, content);
    console.log(
      `[generate-items-index] ${entries.length} item(s): ${entries.map((e) => e.moduleName).join(", ")}`
    );
  }
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  generate();
}
